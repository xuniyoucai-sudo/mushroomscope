import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const output = join(root, 'public', 'ads.txt');
const marker = '# Generated by scripts/prepare-adsense.mjs';
const candidate = process.env.PUBLIC_ADSENSE_PUBLISHER_ID?.trim() ?? '';

if (!candidate) {
  let existing = '';
  try { existing = await readFile(output, 'utf8'); } catch (error) {
    if (error?.code !== 'ENOENT') throw error;
  }
  if (existing.startsWith(marker)) await rm(output);
  console.log('AdSense disabled: PUBLIC_ADSENSE_PUBLISHER_ID is blank; ads.txt was not generated.');
  process.exit(0);
}

if (!/^ca-pub-\d{16}$/.test(candidate)) {
  throw new Error('PUBLIC_ADSENSE_PUBLISHER_ID must match ca-pub- followed by exactly 16 digits.');
}

await mkdir(join(root, 'public'), { recursive: true });
const sellerId = candidate.replace(/^ca-/, '');
await writeFile(output, `${marker}\ngoogle.com, ${sellerId}, DIRECT, f08c47fec0942fa0\n`, 'utf8');
console.log(`Generated ads.txt for ${candidate.slice(0, 7)}…${candidate.slice(-4)}.`);
